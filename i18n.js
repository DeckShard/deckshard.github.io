/* Lingua dell'interfaccia. L'app è scritta in italiano; l'inglese viene
   applicato sul DOM: ogni "unità di testo" (un elemento con solo testo e
   formattazione in linea, oppure un singolo nodo di testo) e gli attributi
   placeholder/title/aria-label/alt vengono cercati nel dizionario EN, prima
   per corrispondenza esatta e poi per schema con segnaposto {1} {2} …
   (es. «{1} pesca {2}.» → «{1} draws {2}.»). Un MutationObserver traduce
   ciò che viene ridisegnato; confirm/prompt passano dal dizionario. Le carte
   restano nella lingua stampata. Il dizionario EN è in fondo al file.      */

const INLINE = new Set(["B", "I", "EM", "STRONG", "CODE", "SMALL", "SUP", "SUB", "BR", "U", "S", "A", "KBD"]);
const ATTRS = ["placeholder", "title", "aria-label", "alt"];
const SKIP = new Set(["SCRIPT", "STYLE", "TEXTAREA", "OPTION_", "SVG"]);
const norm = s => s.replace(/\s+/g, " ").trim();

let lang = "it", exact = new Map(), patterns = [], byFirst = new Map();
function compile(dict){
  exact = new Map(); patterns = []; byFirst = new Map();
  for(const [k, v] of Object.entries(dict)){
    const key = norm(k);
    if(!/\{\d+\}/.test(key)){ exact.set(key, v); continue; }
    const parts = key.split(/(\{\d+\})/);
    let rx = "^", order = [];
    for(const p of parts){ const m = p.match(/^\{(\d+)\}$/); if(m){ rx += "([\\s\\S]+?)"; order.push(+m[1]); } else rx += p.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }
    rx += "$";
    const tok = key.split(" ")[0]; const fw = tok.includes("{") ? "" : tok;   // schemi che iniziano con un segnaposto: nel gruppo generico
    const pat = { rx: new RegExp(rx), order, out: v };
    pat.lit = key.replace(/\{\d+\}/g, "").length;
    patterns.push(pat);
    (byFirst.get(fw) || byFirst.set(fw, []).get(fw)).push(pat);
  }
  for(const arr of byFirst.values()) arr.sort((a, b) => b.lit - a.lit);   // prima gli schemi più specifici
}
/* inglese: dopo «You» il verbo perde la -s della terza persona; «3º» → «3rd» */
const IRR = { is: "are", has: "have", does: "do", goes: "go", was: "were" };
function fixEn(s){
  s = s.replace(/^You (\w+?)(s)\b/, (m, v) => { const w = v + "s"; if(IRR[w]) return "You " + IRR[w]; if(/(ss|sh|ch|x|o)es$/.test(w)) return "You " + w.slice(0, -2); if(/ies$/.test(w)) return "You " + w.slice(0, -3) + "y"; return "You " + v; });
  s = s.replace(/^You (is|has|does|goes|was)\b/, (m, v) => "You " + IRR[v]);
  return s.replace(/(\d+)º/g, (m, n) => { const k = +n % 100, s2 = k >= 11 && k <= 13 ? "th" : ["th", "st", "nd", "rd"][k % 10] || "th"; return n + s2; });
}
export function tr(text){
  if(lang === "it" || !text) return text;
  const key = norm(text);
  if(!key) return text;
  const hit = exact.get(key); if(hit != null) return hit;
  const fw = (key.match(/^(\S+)/) || [])[1] || "";
  const cands = [...(byFirst.get(fw) || []), ...(byFirst.get("") || [])];
  for(const p of cands){
    const m = key.match(p.rx); if(!m) continue;
    let out = p.out; p.order.forEach((n, i) => { out = out.split("{" + n + "}").join(tr(m[i + 1])); });
    return fixEn(out);
  }
  return text;
}
/* un elemento è un'unità se contiene testo e solo tag in linea (senza figli propri) */
function isUnit(el){
  let text = false;
  for(const n of el.childNodes){
    if(n.nodeType === 3){ if(n.nodeValue.trim()) text = true; continue; }
    if(n.nodeType !== 1) continue;
    if(!INLINE.has(n.tagName)) return false;
    for(const c of n.childNodes) if(c.nodeType === 1 && !(INLINE.has(c.tagName) && !c.children.length)) return false;
  }
  return text;
}
const done = new WeakSet();
let applying = false;
export function translateTree(root, collect){
  if(lang === "it" && !collect) return;
  const out = collect || null;
  const walk = el => {
    if(el.nodeType !== 1 || SKIP.has(el.tagName) || el.tagName === "svg") return;
    for(const a of ATTRS){ const v = el.getAttribute(a); if(v && v.trim()){ if(out) out.add(norm(v)); else if(!el["__i18n_" + a] || el["__i18n_" + a] !== v){ const t = tr(v); if(t !== v){ el.setAttribute(a, t); el["__i18n_" + a] = t; } } } }
    if(el.tagName === "OPTION" || el.tagName === "BUTTON" && !el.children.length){ unitText(el); return; }
    if(isUnit(el)){ unitText(el); return; }
    for(const n of Array.from(el.childNodes)){
      if(n.nodeType === 3){ if(n.nodeValue.trim()) textNode(n); }
      else if(n.nodeType === 1) walk(n);
    }
  };
  const unitText = el => {
    const html = el.innerHTML;
    if(out){ out.add(norm(html)); if(el.children.length) for(const n of el.childNodes){ if(n.nodeType === 3 && n.nodeValue.trim()) out.add(norm(n.nodeValue)); else if(n.nodeType === 1) out.add(norm(n.innerHTML)); } return; }
    if(done.has(el) && el.__i18nHtml === html) return;
    const t = tr(html);
    if(t !== norm(html) && t !== html){ el.innerHTML = t; }
    else if(el.children.length){   // nessuna corrispondenza per l'intero: traduci i pezzi (testo e tag in linea) uno per uno
      for(const n of Array.from(el.childNodes)){ if(n.nodeType === 3){ if(n.nodeValue.trim()) textNode(n); } else if(n.nodeType === 1){ unitText(n); } }
    }
    done.add(el); el.__i18nHtml = el.innerHTML;
  };
  const textNode = n => {
    if(out){ out.add(norm(n.nodeValue)); return; }
    if(done.has(n)) return;
    const t = tr(n.nodeValue);
    if(t !== norm(n.nodeValue) && t !== n.nodeValue){ const lead = n.nodeValue.match(/^\s*/)[0], trail = n.nodeValue.match(/\s*$/)[0]; n.nodeValue = lead + t + trail; }
    done.add(n);
  };
  applying = true; try{ walk(root); } finally { applying = false; }
}
/* raccolta delle stringhe italiane (per costruire il dizionario) */
export function collectStrings(root = document.body){ const s = new Set(); translateTree(root, s); return [...s]; }

export function currentLang(){ return lang; }
export function initI18n(l){
  lang = l === "en" ? "en" : "it";
  document.documentElement.lang = lang;
  if(lang === "it") return;
  compile(EN);
  translateTree(document.body);
  const mo = new MutationObserver(muts => {
    if(applying) return;
    for(const m of muts){
      if(m.type === "characterData"){ if(m.target.parentNode){ done.delete(m.target); translateTree(m.target.parentNode); } continue; }
      for(const n of m.addedNodes){ if(n.nodeType === 1) translateTree(n); else if(n.nodeType === 3 && n.parentNode){ done.delete(n); translateTree(n.parentNode); } }
    }
  });
  mo.observe(document.body, { childList: true, subtree: true, characterData: true });
  // finestre native
  const _confirm = window.confirm.bind(window), _prompt = window.prompt.bind(window), _alert = window.alert.bind(window);
  window.confirm = m => _confirm(tr(m)); window.prompt = (m, d) => _prompt(tr(m), d); window.alert = m => _alert(tr(m));
  document.title = tr(document.title);
}

